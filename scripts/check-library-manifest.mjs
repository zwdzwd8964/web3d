#!/usr/bin/env node
/**
 * T-145 · the built-in library's manifest, checked.
 *
 * Two constitutional obligations meet in one file, and both are the kind that is only
 * discovered on go-live day if nothing enforces them:
 *
 * **C6 · zero external runtime dependency.** A library entry is just a path. The moment
 * one of them says `https://…`, the editor fetches over the network — on a customer
 * intranet that is a broken panel, and `check-no-external.mjs` cannot see it because the
 * manifest is data, not build output.
 *
 * **Risk V1 · licence contamination.** Every item must name its licence. Not because a
 * string proves anything, but because an item with nowhere to write one is an item nobody
 * asked the question about. The starter content is generated by this repository and is
 * therefore CC0 by construction; a real art pack (H2) is where this actually bites.
 *
 * Also enforces the size budgets from 进化规划 V5, because a library that makes the editor
 * take ten seconds to open is a library nobody turns on.
 *
 * Run: node scripts/check-library-manifest.mjs
 *      node scripts/check-library-manifest.mjs --allow-missing   # no library yet = SKIP
 */
import { existsSync, readFileSync, statSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { makeReport, printReport } from './lib/scan.mjs'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const ALLOW_MISSING = process.argv.includes('--allow-missing')
const LIBRARY = join(ROOT, 'packages/editor/public/library')
const MANIFEST = join(LIBRARY, 'manifest.json')

/** 进化规划 §8 V5 · per-file and total budgets, in bytes. */
const BUDGETS = {
  texture: 2 * 1024 * 1024,
  hdri: 8 * 1024 * 1024,
  model: 8 * 1024 * 1024,
  preview: 256 * 1024,
  total: 40 * 1024 * 1024,
}

const CATEGORIES = ['model', 'texture', 'hdri']
const ID_RE = /^[a-z][a-z0-9-]{2,63}$/
/** Anything with a scheme, a protocol-relative prefix, or an absolute root. */
const NOT_RELATIVE = /^([a-z][a-z0-9+.-]*:|\/\/|\/)/i

const report = makeReport('built-in library manifest', 'C6 + V1')

if (!existsSync(MANIFEST)) {
  if (ALLOW_MISSING) {
    console.log(`SKIP  ${report.article} · ${report.name}  — no library present (run scripts/gen-library-starter.mjs)`)
    process.exit(0)
  }
  console.error(`FAIL  ${report.article} · ${report.name}  — packages/editor/public/library/manifest.json is missing`)
  console.error('      run: node scripts/gen-library-starter.mjs')
  process.exit(1)
}

const raw = readFileSync(MANIFEST, 'utf8')
let manifest
try {
  manifest = JSON.parse(raw)
} catch (error) {
  console.error(`FAIL  ${report.article} · ${report.name}  — manifest.json is not valid JSON: ${error.message}`)
  process.exit(1)
}

const at = (message) => report.add(MANIFEST, 1, message)

if (manifest.version !== 1) at(`unsupported manifest version: ${JSON.stringify(manifest.version)} (expected 1)`)
if (!Array.isArray(manifest.items)) {
  at('manifest.items must be an array')
  process.exit(printReport(report, ROOT))
}

/**
 * A URL anywhere in the manifest text, including in fields this check does not know about.
 *
 * The per-field checks below only see the fields they were told about; this catches a
 * `thumbnail: "https://…"` added later by someone who did not update this script — which
 * is exactly how a guard quietly stops covering the thing it was written for.
 */
for (const [i, line] of raw.split('\n').entries()) {
  const match = /https?:\/\/[^\s"']+/.exec(line)
  if (match) report.add(MANIFEST, i + 1, `external URL in the manifest: ${match[0].slice(0, 120)}`)
}

const seen = new Set()
let totalBytes = 0
const byCategory = new Map()

for (const [i, item] of manifest.items.entries()) {
  const where = `items[${i}]`
  const id = item?.id

  if (typeof id !== 'string' || !ID_RE.test(id)) {
    at(`${where}.id must be lower-kebab, 3–64 chars: ${JSON.stringify(id)}`)
  } else if (seen.has(id)) {
    at(`${where}.id is a duplicate: ${id}`)
  } else {
    seen.add(id)
  }

  if (typeof item?.name !== 'string' || item.name.trim() === '') at(`${where}.name is required`)
  if (!CATEGORIES.includes(item?.category)) {
    at(`${where}.category must be one of ${CATEGORIES.join(' | ')}: ${JSON.stringify(item?.category)}`)
  }
  // The whole point of V1: an entry with no licence field is an entry nobody asked about.
  if (typeof item?.license !== 'string' || item.license.trim() === '') {
    at(`${where}.license is required — see docs/LICENSES_LIBRARY.md`)
  }
  if (typeof item?.author !== 'string' || item.author.trim() === '') at(`${where}.author is required`)

  for (const field of ['file', 'preview']) {
    const value = item?.[field]
    if (typeof value !== 'string' || value === '') {
      at(`${where}.${field} is required`)
      continue
    }
    if (NOT_RELATIVE.test(value)) {
      at(`${where}.${field} must be a path relative to the library root, never a URL: ${value}`)
      continue
    }
    if (value.includes('..')) {
      at(`${where}.${field} must not escape the library root: ${value}`)
      continue
    }
    const path = join(LIBRARY, value)
    if (!existsSync(path)) {
      at(`${where}.${field} points at a file that is not there: ${value}`)
      continue
    }
    const bytes = statSync(path).size
    totalBytes += bytes
    const budget = field === 'preview' ? BUDGETS.preview : BUDGETS[item.category]
    if (budget !== undefined && bytes > budget) {
      at(`${where}.${field} is ${kb(bytes)}, over the ${kb(budget)} budget for ${field === 'preview' ? 'previews' : item.category}`)
    }
  }

  byCategory.set(item?.category, (byCategory.get(item?.category) ?? 0) + 1)
}

if (totalBytes > BUDGETS.total) {
  at(`library totals ${kb(totalBytes)}, over the ${kb(BUDGETS.total)} budget (进化规划 V5)`)
}

report.filesScanned = manifest.items.length * 2 + 1
report.note(`${manifest.items.length} item(s): ${[...byCategory].map(([c, n]) => `${n} ${c}`).join(', ')}`)
report.note(`${kb(totalBytes)} of ${kb(BUDGETS.total)} budget`)

process.exit(printReport(report, ROOT))

function kb(bytes) {
  return bytes >= 1024 * 1024 ? `${(bytes / 1024 / 1024).toFixed(1)} MB` : `${(bytes / 1024).toFixed(1)} KB`
}
